function load(name) {
  const p = path.join(DATA_DIR, name);
  return existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : null;
}

function fmtOccurrences(entry, more) {
  const occ = entry.occurrences || [];
  const shown = occ.slice(0, 3).map((o) => `\`${o.file}:${o.line}\``);
  const suffix = occ.length > 3 ? `<br>${more}` : '';
  return shown.join('<br>') + suffix;
}

/** 按给定语言渲染整份报告（不含隐藏 marker） */
function render(extracted, scan, t) {
  const uniqueCount = extracted?.unique_count || 0;
  const lines = [t.title, ''];

  if (!scan) {
    lines.push(t.missingScan(uniqueCount), '', t.generated);
    return lines;
  }

  const results = scan.results || [];
  const counts = {
    malicious: results.filter((r) => r.verdict === 'malicious').length,
    suspicious: results.filter((r) => r.verdict === 'suspicious').length,
    clean: results.filter((r) => r.verdict === 'clean').length,
    not_scanned: results.filter((r) => r.verdict === 'not_scanned').length,
  };

  if (uniqueCount === 0) {
    lines.push(t.noLinks, '', t.generated);
    return lines;
  }

  if (counts.malicious > 0) {
    lines.push(t.malicious(counts.malicious), t.fixHint);
  } else if (counts.suspicious > 0) {
    lines.push(t.suspicious(counts.suspicious), t.fixHint);
  } else {
    lines.push(t.passed);
  }
  lines.push('');

  const rows = results
    .filter((r) => r.verdict !== 'clean')
    .slice(0, MAX_TABLE_ROWS)
    .map((r) => {
      const link = r.reportLink ? `[${r.url}](${r.reportLink})` : r.url;
      const detail =
        r.verdict === 'not_scanned'
          ? r.reason || t.unknownReason
          : t.detail(r.malicious, r.suspicious);
      return `| ${t.label[r.verdict]} | ${link} | ${fmtOccurrences(r, t.more)} | ${detail} |`;
    });
  if (rows.length) {
    lines.push(`| ${t.thVerdict} | ${t.thLink} | ${t.thSource} | ${t.thDetail} |`, '|---|---|---|---|', ...rows, '');
  }

  for (const [verdict, summary] of [
    ['malicious', t.detMalicious],
    ['suspicious', t.detSuspicious],
  ]) {
    const hits = results.filter((r) => r.verdict === verdict && r.engines?.length);
    if (hits.length) {
      lines.push('<details>', `<summary>${summary}</summary>`, '');
      for (const r of hits) {
        lines.push(`- \`${r.url}\``);
        for (const e of r.engines) lines.push(`  - ${e}`);
      }
      lines.push('', '</details>', '');
    }
  }

  const notes = [];
  if (counts.clean > 0) notes.push(t.noteClean(counts.clean));
  if (counts.not_scanned > 0) notes.push(t.noteNotScanned(counts.not_scanned));
  if (extracted?.overflow?.length) {
    const sample =
      extracted.overflow.slice(0, 3).join(', ') + (extracted.overflow.length > 3 ? ' ...' : '');
    notes.push(t.noteOverflow(extracted.overflow.length, sample));
  }
  if (extracted?.allowlisted?.length) notes.push(t.noteAllowlisted(extracted.allowlisted.length));
  if (notes.length) {
    if (lines[lines.length - 1] !== '') lines.push('');
    lines.push(t.note(notes));
  }

  lines.push('', t.rule);
  return lines;
}

function buildComment(extracted, scan) {
  return [REPORT_MARKER, ...render(extracted, scan, T.zh), '', '---', '', ...render(extracted, scan, T.en)].join(
    '\n'
  );
}

async function main() {
  const extracted = load('extracted.json');
  const scan = load('scan-results.json');
  const body = buildComment(extracted, scan);

  if (process.env.URL_SCAN_DRY_RUN === '1') {
    console.log('--- DRY RUN 评论内容 ---');
    console.log(body);
  } else {
    await upsertPrComment(body); // 覆盖进度占位评论（同 marker）
  }

  if (process.env.GITHUB_STEP_SUMMARY) {
    appendFileSync(process.env.GITHUB_STEP_SUMMARY, body.replace(REPORT_MARKER, ''));
  }

  const malicious = scan?.results?.filter((r) => r.verdict === 'malicious').length || 0;
  const suspicious = scan?.results?.filter((r) => r.verdict === 'suspicious').length || 0;
  if (malicious > 0 || suspicious > 0) {
    console.error(`发现 ${malicious} 个恶意、${suspicious} 个可疑链接，任务失败以阻止合并（运行期无人工放行）。`);
    process.exit(1);
  }
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
